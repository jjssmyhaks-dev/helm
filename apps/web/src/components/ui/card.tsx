import * as React from 'react';
import { cn } from '@/lib/utils';

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hover?: boolean; glow?: boolean }
>(({ className, hover = false, glow = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      'rounded-2xl border border-surface-300/50 bg-surface-100/50 backdrop-blur-xl',
      hover && 'transition-all duration-300 hover:border-surface-400/50 hover:bg-surface-100/80 hover:shadow-lg hover:shadow-black/10',
      glow && 'hover:border-helm-500/30 hover:shadow-lg hover:shadow-helm-500/5',
      className
    )}
    {...props}
  />
));
Card.displayName = 'Card';

